"""Generate repository-local agent rules from a pinned Git source."""
import argparse
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import tempfile
from zipfile import ZipFile

CONFIG = "agent-standards.json"
LOCK = "agent-standards.lock.json"
MANIFEST = ".agent-standards/manifest.json"
MARKER = "<!-- Generated by agent-standards. Edit AGENTS.local.md for project rules. -->"
STACK_PATHS = {
    "react": "frontend/react",
    "nestjs-prisma": "backend/nestjs",
    "fastapi": "backend/fastapi",
}


def git(directory, *args):
    result = subprocess.run(
        ["git", "-C", str(directory), *args], capture_output=True, check=False
    )
    if result.returncode:
        raise ValueError(result.stderr.decode("utf-8", errors="replace").strip())
    return result.stdout


def snapshot(source, revision):
    if not revision or revision.startswith("-"):
        raise ValueError("Invalid Git revision")
    local = Path(source)
    if local.is_dir():
        commit = git(local, "rev-parse", "--verify", f"{revision}^{{commit}}").decode().strip()
        archive = git(local, "archive", "--format=zip", commit, "shared", "frontend", "backend")
    else:
        with tempfile.TemporaryDirectory() as folder:
            git(folder, "init", "-q")
            git(folder, "fetch", "--quiet", "--depth=1", "--", source, revision)
            commit = git(folder, "rev-parse", "FETCH_HEAD^{commit}").decode().strip()
            archive = git(folder, "archive", "--format=zip", commit, "shared", "frontend", "backend")
    with ZipFile(io.BytesIO(archive)) as files:
        return commit, {name: files.read(name) for name in files.namelist() if not name.endswith("/")}


def project_path(root, name):
    relative = PurePosixPath(name)
    if (
        relative.is_absolute()
        or relative.as_posix() != name
        or any(part in ("..", ".git", ".agent-standards") or ":" in part or "\\" in part
               for part in relative.parts)
    ):
        raise ValueError(f"Invalid project scope: {name}")
    target = root.joinpath(*relative.parts)
    if target.resolve() != target:
        raise ValueError(f"Project scope traverses a link: {name}")
    return target


def render(root, config, upstream):
    scopes = config["scopes"]
    if not isinstance(scopes, dict) or not scopes:
        raise ValueError("Configure at least one scope")
    destinations = set()
    for scope, stack in scopes.items():
        if stack not in STACK_PATHS:
            raise ValueError(f"Unknown stack: {stack}")
        directory = project_path(root, scope)
        key = os.path.normcase(str(directory))
        if key in destinations:
            raise ValueError(f"Duplicate scope: {scope}")
        destinations.add(key)

    selected = ("shared/", *(f"{STACK_PATHS[stack]}/" for stack in set(scopes.values())))
    files = {
        f".agent-standards/{name}": data for name, data in upstream.items()
        if name.startswith(selected)
    }
    core = upstream["shared/AGENTS.md"].decode("utf-8").strip()
    for scope in sorted(set(scopes) | {"."}):
        directory = project_path(root, scope)
        prefix = Path(os.path.relpath(root / ".agent-standards", directory)).as_posix()
        stack = scopes.get(scope)
        sections = [MARKER]
        if scope == ".":
            sections.append(core)
        else:
            parent_rules = Path(os.path.relpath(root / "AGENTS.md", directory)).as_posix()
            sections.append(f"同时遵守仓库根目录的 `{parent_rules}`。")
        if stack:
            stack_path = STACK_PATHS[stack]
            sections.extend([
                upstream[f"{stack_path}/AGENTS.md"].decode("utf-8").strip(),
                f"本技术栈的详细规范与示例位于 `{prefix}/{stack_path}/`。"
                " 本入口中的通用与技术栈规则优先于参考文档。",
            ])
        local = directory / "AGENTS.local.md"
        if local.is_file():
            sections.extend(["## 项目补充规则", local.read_text(encoding="utf-8").strip()])
        name = (directory / "AGENTS.md").relative_to(root).as_posix()
        files[name] = ("\n\n".join(sections) + "\n").encode("utf-8")
    files[MANIFEST] = json_bytes(sorted(files))
    return files


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def managed_path(root, name):
    target = root / name
    if target.resolve() != target or not target.is_relative_to(root) or ".." in Path(name).parts:
        raise ValueError(f"Unsafe output path: {name}")
    return target


def old_outputs(root):
    path = managed_path(root, MANIFEST)
    if not path.exists():
        return set()
    names = read_json(path)
    if not isinstance(names, list) or any(
        not isinstance(name, str)
        or (not name.startswith(".agent-standards/") and Path(name).name != "AGENTS.md")
        for name in names
    ):
        raise ValueError("Invalid generated file manifest")
    return set(names) | {MANIFEST}


def replace(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as temp:
        temporary = Path(temp.name)
        temp.write(data)
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def reconcile(root, files, old, check):
    stale = old - files.keys()
    changes = {}
    for name, data in files.items():
        path = managed_path(root, name)
        current = path.read_bytes() if path.exists() else None
        if current == data:
            continue
        if not check and current is not None:
            if Path(name).name == "AGENTS.md" and not name.startswith(".agent-standards/"):
                if not current.startswith(MARKER.encode()):
                    raise ValueError(f"Move existing {name} to AGENTS.local.md before syncing")
            elif name not in old:
                raise ValueError(f"Existing file is outside the generated manifest: {name}")
        changes[name] = data
    removals = []
    for name in sorted(stale):
        path = managed_path(root, name)
        if path.exists():
            if not name.startswith(".agent-standards/") and not path.read_bytes().startswith(MARKER.encode()):
                raise ValueError(f"Refusing to remove handwritten file: {name}")
            removals.append(name)
    if check:
        if changes or removals:
            raise ValueError("Generated files differ: " + ", ".join(sorted(set(changes) | set(removals))))
        return
    # Keep the previous manifest until writes and stale-file cleanup succeed.
    for name, data in changes.items():
        if name != MANIFEST:
            replace(managed_path(root, name), data)
    for name in removals:
        managed_path(root, name).unlink()
    if MANIFEST in changes:
        replace(managed_path(root, MANIFEST), changes[MANIFEST])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path.cwd())
    commands = parser.add_subparsers(dest="command", required=True)
    init = commands.add_parser("init")
    init.add_argument("--source", required=True)
    init.add_argument("--version", required=True)
    selection = init.add_mutually_exclusive_group(required=True)
    selection.add_argument("--stack", choices=STACK_PATHS)
    selection.add_argument("--scope", action="append", metavar="PATH=STACK")
    upgrade = commands.add_parser("upgrade")
    upgrade.add_argument("--version", required=True)
    commands.add_parser("sync")
    commands.add_parser("check")
    args = parser.parse_args()

    try:
        root = args.project.resolve(strict=True)
        config_path = managed_path(root, CONFIG)
        lock_path = managed_path(root, LOCK)
        if args.command == "init":
            if config_path.exists() or lock_path.exists():
                raise ValueError("Project already has standards configuration")
            source = args.source
            local_source = Path(source).expanduser()
            if local_source.exists():
                source = str(local_source.resolve())
            pairs = [scope.split("=", 1) for scope in args.scope or []]
            scopes = {".": args.stack} if args.stack else dict(pairs)
            if pairs and len(scopes) != len(pairs):
                raise ValueError("Duplicate scope")
            config = {"source": source, "scopes": scopes}
        else:
            config = read_json(config_path)

        pin = args.command in {"init", "upgrade"}
        if pin:
            commit, upstream = snapshot(config["source"], args.version)
            lock = {"source": config["source"], "version": args.version, "commit": commit}
        else:
            lock = read_json(lock_path)
            if lock["source"] != config["source"] or not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", lock["commit"]):
                raise ValueError("Lock does not match source or has an invalid commit")
            commit, upstream = snapshot(lock["source"], lock["commit"])
            if commit != lock["commit"]:
                raise ValueError("Fetched commit differs from lock")

        files = render(root, config, upstream)
        reconcile(root, files, old_outputs(root), args.command == "check")
        if args.command == "init":
            replace(config_path, json_bytes(config))
        if pin:
            replace(lock_path, json_bytes(lock))
        print(f"{args.command}: {lock['version']} ({commit})")
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"agent-standards: {error}\n")


if __name__ == "__main__":
    main()
